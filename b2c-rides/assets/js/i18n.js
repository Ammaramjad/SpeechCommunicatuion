window.RL = {
  lang: localStorage.getItem("rl-lang") || "zh-TW",
  t(k) {
    return (I18N[this.lang] || I18N["zh-TW"])[k] || I18N.en[k] || k;
  },
  loc(p) {
    if (!p) return "";
    return this.lang === "en" ? (p.name_en || p.name_zh) : (p.name_zh || p.name_en);
  },
  car(v) {
    if (!v) return "";
    return this.lang === "en" ? (v.name_en || v.name_zh) : (v.name_zh || v.name_en);
  },
  nt(n) {
    return "NT$ " + Number(n || 0).toLocaleString("zh-TW");
  },
  toggle() {
    this.lang = this.lang === "zh-TW" ? "en" : "zh-TW";
    localStorage.setItem("rl-lang", this.lang);
    location.reload();
  },
};

window.API = {
  async get(path) {
    const r = await fetch(path);
    if (!r.ok) throw new Error(await r.text());
    return r.json();
  },
  async post(path, body) {
    const r = await fetch(path, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body || {}),
    });
    if (!r.ok) throw new Error(await r.text());
    return r.json();
  },
};
